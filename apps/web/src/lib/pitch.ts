/** Which pitch section (1–5) matches a given route. Unmapped routes fall back to 1. */
export function screenIdForPath(pathname: string): 1 | 2 | 3 | 4 | 5 {
  if (pathname.startsWith("/numbers")) return 2;
  if (pathname.startsWith("/tastes")) return 3;
  if (/^\/plan\/[^/]+\/cart/.test(pathname)) return 5;
  if (pathname.startsWith("/plan") || pathname.startsWith("/plans")) return 4;
  return 1; // /, /goal, /dev, everything else
}
